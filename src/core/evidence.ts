import { readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { findSeededBug } from './bugs.ts';
import { PHASES, type Phase, type PhaseRecord, type RunJournal } from './types.ts';
import { remediation } from './verdict.ts';
import { ensureDir, paths, relative } from '../util/paths.ts';

/** Files Playwright drops that are worth surfacing as evidence. */
const INTERESTING = /\.(zip|png|webm|md)$/i;

export interface EvidenceFile {
  label: string;
  path: string;
}

async function walk(dir: string): Promise<string[]> {
  const found: string[] = [];
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return found;
  }

  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      // The generated HTML report is a whole site; link the directory, not every asset.
      if (entry.name === 'html-report') {
        found.push(full);
        continue;
      }
      found.push(...(await walk(full)));
    } else if (INTERESTING.test(entry.name)) {
      found.push(full);
    }
  }
  return found;
}

export async function collectEvidence(ticketId: string, phase: Phase): Promise<EvidenceFile[]> {
  const dir = paths.evidenceDir(ticketId, phase);
  const files = await walk(dir);
  return files.map((path) => ({ label: describe(path), path }));
}

function describe(path: string): string {
  if (path.endsWith('.zip')) return 'Playwright trace';
  if (path.endsWith('.webm')) return 'video';
  if (path.endsWith('html-report')) return 'HTML report';
  if (path.endsWith('.png')) return 'screenshot';
  return 'artifact';
}

const PHASE_BLURB: Record<Phase, string> = {
  red: 'defect armed — the test must fail',
  green: 'defect disarmed — the test must pass',
  guard: 'defect re-armed — the test must fail again',
};

const MARK: Record<string, string> = {
  reproduced: '✅',
  fixed: '✅',
  guarding: '✅',
  vacuous: '❌',
  misfire: '❌',
  unfixed: '❌',
  'not-guarding': '❌',
  inconclusive: '⚠️',
};

function statusWord(record: PhaseRecord): string {
  return record.outcome.status === 'passed' ? 'passed' : record.outcome.status;
}

/**
 * Render the cycle as a ticket comment.
 *
 * Written to be read by whoever triages the ticket, so the verdicts lead and the
 * raw error output is tucked into collapsed blocks.
 */
export async function renderReport(journal: RunJournal): Promise<string> {
  const lines: string[] = [];
  const headline = journal.certified
    ? '✅ Regression cycle certified'
    : '⚠️ Regression cycle incomplete';

  lines.push(`## ${headline}`, '');
  lines.push(`**Ticket:** ${journal.ticketTitle}`);
  if (journal.specPath) lines.push(`**Regression spec:** \`${relative(journal.specPath)}\``);

  if (journal.seededBug) {
    const bug = findSeededBug(journal.seededBug);
    lines.push(`**Defect under test:** \`${journal.seededBug}\`${bug ? ` — ${bug.rootCause}` : ''}`);
  }
  lines.push('');

  lines.push('| Phase | Condition | Run | Verdict |');
  lines.push('| --- | --- | --- | --- |');
  for (const phase of PHASES) {
    const record = journal.phases[phase];
    if (!record) {
      lines.push(`| \`${phase}\` | ${PHASE_BLURB[phase]} | — | not run |`);
      continue;
    }
    lines.push(
      `| \`${phase}\` | ${PHASE_BLURB[phase]} | ${statusWord(record)} | ${MARK[record.verdict] ?? ''} ${record.verdict} |`,
    );
  }
  lines.push('');

  if (journal.certified) {
    lines.push(
      'The test was proven to fail on the reported defect, pass once it was fixed, and fail again when the defect was reintroduced. It is safe to keep as a permanent regression guard.',
      '',
    );
  }

  for (const phase of PHASES) {
    const record = journal.phases[phase];
    if (!record) continue;

    lines.push(`### \`${phase}\` — ${record.verdict}`, '');
    lines.push(record.reason, '');

    if (record.armedBugs.length > 0) {
      lines.push(`Armed defects: \`${record.armedBugs.join('`, `')}\``, '');
    }

    if (record.outcome.failureMessage) {
      lines.push('<details><summary>Failure output</summary>', '', '```');
      lines.push(record.outcome.failureMessage);
      lines.push('```', '', '</details>', '');
    }

    const files = await collectEvidence(journal.ticketId, phase);
    if (files.length > 0) {
      lines.push('Evidence:');
      for (const file of files) {
        lines.push(`- ${file.label} — \`${relative(file.path)}\``);
      }
      lines.push('');
    }

    const fix = record.ok ? null : remediation(record.verdict, record.outcome.classification);
    if (fix) lines.push(`> **Next step:** ${fix}`, '');
  }

  lines.push('---', '', '<sub>Generated by the Bugproof repro & regression agent.</sub>');
  return lines.join('\n');
}

export async function writeReportFile(journal: RunJournal, markdown: string): Promise<string> {
  const dir = await ensureDir(join(paths.evidence, journal.ticketId));
  const file = join(dir, 'report.md');
  await writeFile(file, markdown, 'utf8');
  return file;
}
